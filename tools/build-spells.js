#!/usr/bin/env node
/* Builds js/spells-data.js from the Complete Compendium 5.5e XML (Fight Club format).
   Usage: node tools/build-spells.js <compendium.xml> [out.js]
   Keeps spells tagged [5.5e] that list at least one of the 12 core 2024 PHB classes,
   with per-level <roll> scaling data used by the spell level selector. */
"use strict";
const fs = require("fs");
const path = require("path");

const CORE = ["Barbarian", "Bard", "Cleric", "Druid", "Fighter", "Monk", "Paladin", "Ranger", "Rogue", "Sorcerer", "Warlock", "Wizard"];
const MAX_PARA = 700;

const xmlPath = process.argv[2];
const outPath = process.argv[3] || path.join(__dirname, "..", "js", "spells-data.js");
if (!xmlPath) { console.error("usage: node tools/build-spells.js <compendium.xml> [out.js]"); process.exit(1); }
const xml = fs.readFileSync(xmlPath, "utf8");

function decode(s) {
  return s
    .replace(/&#x([0-9a-fA-F]+);/g, (_, h) => String.fromCodePoint(parseInt(h, 16)))
    .replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(parseInt(d, 10)))
    .replace(/&quot;/g, '"').replace(/&apos;/g, "'").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&amp;/g, "&");
}
function clean(s) {
  return decode(s).replace(/<[^>]+>/g, " ").replace(/[ \t]+/g, " ").replace(/\s*\n\s*/g, " ").trim();
}

const spells = [];
const seen = new Set();
const re = /<spell>([\s\S]*?)<\/spell>/g;
let m;
while ((m = re.exec(xml))) {
  const body = m[1];
  const nameM = body.match(/<name>([^<]+)<\/name>/);
  if (!nameM) continue;
  const rawName = nameM[1];
  if (!/ \[5\.5e\]$/.test(rawName)) continue;
  const name = rawName.replace(/ \[5\.5e\]$/, "");
  if (/\((HB|UA|Legacy)\)/i.test(name) || /\(([A-Z]{2,4})\)/.test(name)) continue;
  if (seen.has(name)) continue;
  seen.add(name);

  const field = (tag) => { const f = body.match(new RegExp("<" + tag + ">([\\s\\S]*?)</" + tag + ">")); return f ? f[1].trim() : ""; };
  const level = parseInt(field("level"), 10) || 0;
  const classesRaw = field("classes");
  const classes = classesRaw.split(",").map((c) => c.trim().replace(/ \([^)]*\)$/, "").replace(/ \[5\.5e\]$/, "").trim())
    .filter((c) => CORE.includes(c));
  if (!classes.length) continue;

  const texts = [...body.matchAll(/<text>([\s\S]*?)<\/text>/g)].map((t) => clean(t[1]));
  const paras = texts.join("\n\n").split(/\n\s*\n/).map(clean).filter((p) => p && !/^Source:/i.test(p))
    .map((p) => (p.length > MAX_PARA ? p.slice(0, MAX_PARA).trim() + "…" : p));
  if (!paras.length) continue;

  const rolls = [...body.matchAll(/<roll description="([^"]*)" level="(\d+)">([^<]+)<\/roll>/g)]
    .map((r) => ({ description: r[1], level: parseInt(r[2], 10), dice: r[3].trim() }));

  spells.push({
    name,
    level,
    school: field("school"),
    time: field("time"),
    range: field("range"),
    components: field("components"),
    duration: field("duration"),
    classes: [...new Set(classes)],
    paras,
    rolls
  });
}

spells.sort((a, b) => a.level - b.level || a.name.localeCompare(b.name));

const out = "/* Generated by tools/build-spells.js from the Complete Compendium 5.5e XML.\n" +
  "   Core 2024 PHB spells with per-level roll scaling. Do not edit by hand. */\n" +
  "window.DM_SPELLS = " + JSON.stringify(spells, null, 1) + ";\n";
fs.writeFileSync(outPath, out);
const rollCount = spells.reduce((s, x) => s + x.rolls.length, 0);
console.log("wrote " + outPath + ": " + spells.length + " spells, " + rollCount + " level rolls, " + (out.length / 1024).toFixed(0) + " KB");
const fb = spells.find((s) => s.name === "Fireball");
const fbo = spells.find((s) => s.name === "Fire Bolt");
console.log("Fireball:", fb.level, fb.classes.join("/"), "rolls:", fb.rolls.map((r) => r.level + ":" + r.dice).join(" "));
console.log("Fire Bolt:", fbo.level, fbo.classes.join("/"), "rolls:", fbo.rolls.map((r) => r.level + ":" + r.dice).join(" "));
