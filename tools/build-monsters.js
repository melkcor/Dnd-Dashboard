#!/usr/bin/env node
/* Builds js/monsters-data.js from the Complete Compendium 5.5e XML (Fight Club format).
   Usage: node tools/build-monsters.js <compendium.xml> [out.js]
   Keeps monsters tagged [5.5e] with a full stat block (ac/hp/cr). */
"use strict";
const fs = require("fs");
const path = require("path");

const MAX_TEXT = 480;

const xmlPath = process.argv[2];
const outPath = process.argv[3] || path.join(__dirname, "..", "js", "monsters-data.js");
if (!xmlPath) { console.error("usage: node tools/build-monsters.js <compendium.xml> [out.js]"); process.exit(1); }
const xml = fs.readFileSync(xmlPath, "utf8");

function decode(s) {
  return s
    .replace(/&#x([0-9a-fA-F]+);/g, (_, h) => String.fromCodePoint(parseInt(h, 16)))
    .replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(parseInt(d, 10)))
    .replace(/&quot;/g, '"').replace(/&apos;/g, "'").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&amp;/g, "&");
}
function clean(s) {
  return decode(s).replace(/<[^>]+>/g, " ").replace(/[ \t]+/g, " ").replace(/\s*\n\s*/g, " ").trim();
}
function trunc(s) {
  s = clean(s);
  return s.length > MAX_TEXT ? s.slice(0, MAX_TEXT).trim() + "…" : s;
}
function field(body, tag) {
  const m = body.match(new RegExp("<" + tag + ">([\\s\\S]*?)</" + tag + ">"));
  return m ? m[1].trim() : "";
}
function namedBlocks(body, tag) {
  const out = [];
  const re = new RegExp("<" + tag + ">([\\s\\S]*?)</" + tag + ">", "g");
  let m;
  while ((m = re.exec(body))) {
    const b = m[1];
    const name = (b.match(/<name>([^<]+)<\/name>/) || [])[1] || "";
    const texts = [...b.matchAll(/<text>([\s\S]*?)<\/text>/g)].map((t) => trunc(t[1]));
    const attacks = [...b.matchAll(/<attack>([\s\S]*?)<\/attack>/g)].map((a) => trunc(a[1]));
    if (!name) continue;
    out.push({ name: clean(name), text: texts.join(" "), attacks });
  }
  return out;
}

const monsters = [];
const seen = new Set();
const re = /<monster>([\s\S]*?)<\/monster>/g;
let m;
while ((m = re.exec(xml))) {
  const body = m[1];
  const rawName = field(body, "name");
  if (!/ \[5\.5e\]$/.test(rawName)) continue;
  const name = rawName.replace(/ \[5\.5e\]$/, "");
  if (seen.has(name)) continue;
  const ac = field(body, "ac");
  const hp = field(body, "hp");
  const cr = field(body, "cr");
  if (!ac || !hp || !cr) continue;
  seen.add(name);

  const mon = {
    name,
    size: field(body, "size"),
    type: clean(field(body, "type")),
    alignment: clean(field(body, "alignment")),
    ac,
    hp,
    speed: clean(field(body, "speed")),
    str: field(body, "str"), dex: field(body, "dex"), con: field(body, "con"),
    int: field(body, "int"), wis: field(body, "wis"), cha: field(body, "cha"),
    passive: field(body, "passive"),
    saves: clean(field(body, "saves")),
    skills: clean(field(body, "skills")),
    vulnerable: clean(field(body, "vulnerable")),
    resist: clean(field(body, "resist")),
    immune: clean(field(body, "immune")),
    conditionImmune: clean(field(body, "conditionImmune")),
    senses: clean(field(body, "senses")),
    languages: clean(field(body, "languages")),
    cr,
    traits: namedBlocks(body, "trait"),
    actions: namedBlocks(body, "action"),
    reactions: namedBlocks(body, "reaction"),
    legendary: namedBlocks(body, "legendary")
  };
  monsters.push(mon);
}

monsters.sort((a, b) => a.name.localeCompare(b.name));

const out = "/* Generated by tools/build-monsters.js from the Complete Compendium 5.5e XML.\n" +
  "   Monsters tagged [5.5e] with full stat blocks. Do not edit by hand. */\n" +
  "window.DM_MONSTERS = " + JSON.stringify(monsters, null, 1) + ";\n";
fs.writeFileSync(outPath, out);
console.log("wrote " + outPath + ": " + monsters.length + " monsters, " + (out.length / 1024).toFixed(0) + " KB");
const crDist = {};
for (const mo of monsters) crDist[mo.cr] = (crDist[mo.cr] || 0) + 1;
console.log("CR dist (top):", Object.entries(crDist).sort((a, b) => parseFloat(b[0]) - parseFloat(a[0])).slice(0, 8));
