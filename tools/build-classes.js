#!/usr/bin/env node
/* Builds js/classes.js from the Complete Compendium 5.5e XML (Fight Club format).
   Usage: node tools/build-classes.js <path-to-compendium.xml> [out.js]
   Extracts the 12 core 2024 PHB classes: hit die, proficiencies, primary ability,
   and non-optional class features per level (subclass placeholders excluded). */
"use strict";
const fs = require("fs");
const path = require("path");

const CORE = ["Barbarian", "Bard", "Cleric", "Druid", "Fighter", "Monk", "Paladin", "Ranger", "Rogue", "Sorcerer", "Warlock", "Wizard"];
const ABILS = ["Strength", "Dexterity", "Constitution", "Intelligence", "Wisdom", "Charisma"];
const MAX_TEXT = 520;

const xmlPath = process.argv[2];
const outPath = process.argv[3] || path.join(__dirname, "..", "js", "classes.js");
if (!xmlPath) { console.error("usage: node tools/build-classes.js <compendium.xml> [out.js]"); process.exit(1); }
const xml = fs.readFileSync(xmlPath, "utf8");

function decode(s) {
  return s
    .replace(/&#x([0-9a-fA-F]+);/g, (_, h) => String.fromCodePoint(parseInt(h, 16)))
    .replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(parseInt(d, 10)))
    .replace(/&quot;/g, '"').replace(/&apos;/g, "'").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&amp;/g, "&");
}
function clean(s) {
  return decode(s).replace(/<[^>]+>/g, " ").replace(/[ \t]+/g, " ").replace(/\s*\n\s*/g, " ").trim();
}

function extractClass(name) {
  const marker = "<class><name>" + name + " [5.5e]</name>";
  const start = xml.indexOf(marker);
  if (start < 0) { console.error("class not found: " + name); return null; }
  const end = xml.indexOf("</class>", start);
  const cls = xml.slice(start, end);
  const field = (tag) => { const m = cls.match(new RegExp("<" + tag + ">([^<]*)</" + tag + ">")); return m ? m[1].trim() : ""; };

  const savesM = cls.match(/Saving Throw Proficiencies:\s*([^\n<]+)/);
  const saves = savesM ? savesM[1].replace(/ and /g, ",").split(",").map(s => s.trim()).filter(s => ABILS.includes(s)) : [];
  const profList = field("proficiency").split(",").map(s => s.trim()).filter(Boolean);
  const skills = profList.filter(p => !ABILS.includes(p));
  const numSkillsM = field("numSkills") || (cls.match(/Skill Proficiencies: Choose (\d+)/) || [])[1] || "2";
  const primaryM = cls.match(/Primary Ability:\s*([^\n<]+)/);
  const primary = primaryM ? primaryM[1].trim() : "Strength";

  const features = [];
  const alRe = /<autolevel level="(\d+)"[^>]*>([\s\S]*?)<\/autolevel>/g;
  let m;
  while ((m = alRe.exec(cls))) {
    const level = parseInt(m[1], 10);
    const body = m[2];
    const fRe = /<feature([^>]*)>([\s\S]*?)<\/feature>/g;
    let f;
    while ((f = fRe.exec(body))) {
      const attrs = f[1], fbody = f[2];
      const nameM = fbody.match(/<name>([^<]+)<\/name>/);
      if (!nameM) continue;
      let fname = clean(nameM[1]);
      if (/subclass/i.test(fname)) continue;
      if (/optional="YES"/.test(attrs) && !/Ability Score Improvement/i.test(fname)) continue;
      const texts = [...fbody.matchAll(/<text>([\s\S]*?)<\/text>/g)].map(t => clean(t[1]));
      let text = texts.join(" ").replace(/\s+/g, " ").trim();
      if (text.length > MAX_TEXT) text = text.slice(0, MAX_TEXT).trim() + "…";
      fname = fname.replace(/^Level \d+:\s*/, "");
      features.push({ level, name: fname, text });
    }
  }
  features.sort((a, b) => a.level - b.level);
  return {
    id: name.toLowerCase(),
    name,
    hd: parseInt(field("hd"), 10) || 8,
    primary,
    saves,
    skills,
    numSkills: parseInt(numSkillsM, 10) || 2,
    armor: field("armor"),
    weapons: field("weapons"),
    tools: field("tools"),
    features
  };
}

const classes = CORE.map(extractClass).filter(Boolean);
if (classes.length !== 12) { console.error("expected 12 classes, got " + classes.length); process.exit(1); }

const out = "/* Generated by tools/build-classes.js from the Complete Compendium 5.5e XML.\n" +
  "   12 core 2024 PHB classes with per-level features. Do not edit by hand. */\n" +
  "window.DM_CLASSES = " + JSON.stringify(classes, null, 1) + ";\n";
fs.writeFileSync(outPath, out);
let featCount = 0, textBytes = 0;
for (const c of classes) { featCount += c.features.length; textBytes += c.features.reduce((s, f) => s + f.text.length, 0); }
console.log("wrote " + outPath + ": " + classes.length + " classes, " + featCount + " features, " + (out.length / 1024).toFixed(0) + " KB");
